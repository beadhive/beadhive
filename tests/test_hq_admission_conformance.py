"""Replay of hq-service ``conformance/admission/v1`` against the adapter (bh-jwymz).

The corpus is normative for hq-service's lifecycle write routes (``POST /incarnations``, ``PUT``
and ``DELETE /manifests/{host_id}``, ``POST /admissions/{frame}``) and the catalog reads. It has
no Python reference (hq-service's own words: Python has no write endpoints), so this replays it
from the CLIENT's side, as ``tests/test_hq_operator_conformance.py`` does for the operator
routes: a scripted service answers each case with the case's own expectation and the test
asserts the exact bytes the adapter puts on the wire (method, path, body) and what it hands
back, or the port refusal it raises.

Cases whose request a correct client can never produce (a body of the wrong shape, a path that
is not a name, an unknown query parameter) and the ``GET /eligibility`` cases (a verified
authority read answers those, which the corpus does not carry; ``tests/test_hq_api_reads.py``
and ``tests/test_hq_release_eligibility_conformance.py`` cover them) test the service, not the
client. They are skipped by shape, never by name. The server rules themselves (the cases'
``effects``) are asserted by hq-service's own Go runner.

The corpus is read in place from an hq-service export: set ``BH_HQ_SERVICE_CONFORMANCE`` to the
export's root (the directory holding ``conformance/``). With it unset the pinned subset in
``tests/fixtures/hq_service_contract/admission_v1`` is replayed instead (see its PROVENANCE).
"""

from __future__ import annotations

import json
import os
import re
import time
from pathlib import Path
from urllib.parse import parse_qs, urlsplit

import httpx
import pytest

from beadhive.hq_framelease_contracts import ObservationAuthority
from beadhive.hq_port import (
    AdmissionRequest,
    HqDeadline,
    HqOutcomeUnknown,
    HqRefused,
    HqUnavailable,
)
from beadhive.hq_service_adapter import PREFIX, HqServiceAdapter

ENV = "BH_HQ_SERVICE_CONFORMANCE"
PINNED = Path(__file__).parent / "fixtures/hq_service_contract/admission_v1"
HEAD, NEW_HEAD, CONFIG_HEAD, STALE = "a" * 32, "b" * 32, "d" * 32, "9" * 32
SUBSTITUTIONS = {
    "$NEW_CONFIG_HEAD": CONFIG_HEAD,
    "$NEW_HEAD": NEW_HEAD,
    "$STALE": STALE,
    "$HEAD": HEAD,
}
FAILURES = (HqRefused, HqUnavailable, HqOutcomeUnknown, HqDeadline)
NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")


def _corpus() -> Path:
    root = os.environ.get(ENV)
    full = Path(root) / "conformance/admission/v1/cases" if root else None
    return full if full and full.is_dir() else PINNED


def _names() -> list[str]:
    return sorted(p.stem for p in _corpus().glob("*.json") if p.stem != "refusal-codes")


def _fill(text: str) -> str:
    for token, value in SUBSTITUTIONS.items():
        text = text.replace(token, value)
    return text


def _later() -> float:
    return time.monotonic() + 30


def _plan(case: dict) -> tuple[str, dict] | str:
    """``(operation, arguments)`` for a case a client can drive, else why it is not one."""
    request = case["request"]
    split = urlsplit(request["path"])
    parts = split.path.removeprefix(PREFIX).strip("/").split("/")
    query = parse_qs(split.query, keep_blank_values=True)
    if not isinstance(request["body"], str):
        return "the body is generated by the harness (an oversize payload), not sent as is"
    raw = _fill(request["body"]) if request["body"] else ""
    if "$" in raw or "$" in request["path"]:
        return "the request names a value the corpus derives (a principal or digest)"
    try:
        body = json.loads(raw) if raw else None
    except ValueError:
        return "the body is not JSON, which no client sends"
    method, route = request["method"], parts[0]
    if route == "eligibility":
        return "GET /eligibility is answered under a verified authority read the case lacks"
    if len(parts) != 2 or not NAME.match(parts[1]):
        return "the path does not name a frame, host or catalog, which no client sends"
    name = parts[1]
    return _shape(method, route, name, body, query)


def _shape(method: str, route: str, name: str, body, query) -> tuple[str, dict] | str:
    if route == "manifests" and method == "PUT":
        if not isinstance(body, dict) or body.get("host_id") != name or query:
            return "the body is not the manifest of the host the path names"
        return "publish_manifest", {"host": name, "body": body}
    if route == "manifests" and method == "DELETE":
        if body is not None or query:
            return "a withdraw has no body or query"
        return "withdraw_manifest", {"host": name}
    if route == "admissions" and method == "POST":
        keys = set(body) if isinstance(body, dict) else set()
        if query or keys not in (
            {"kind", "expected_revision", "host_id", "public_key"},
            {"kind", "expected_revision"},
        ):
            return "the admission body is not what a client builds"
        if body["kind"] not in ("open", "candidate") or (body["kind"] == "open") != (
            "host_id" in body
        ):
            return "the admission kind and its fields disagree"
        if not all(isinstance(v, str) and v for v in body.values()):
            return "the admission body carries a value no client sends"
        return "admit", {"frame": name, "body": body}
    if route == "release-catalog" and method == "GET":
        if body is not None:
            return "a read has no body"
        if not query:
            return "read_release_catalog", {"catalog": name}
        if set(query) == {"release_id", "release_digest"} and all(
            len(v) == 1 for v in query.values()
        ):
            return "read_release_catalog_row", {"catalog": name, "measured": {
                "id": query["release_id"][0], "digest": query["release_digest"][0]}}  # fmt: skip
        return "the query is not release_id and release_digest"
    return "the route is not driven by the adapter from the wire alone"


def _incarnation(case: dict) -> tuple[str, dict] | str:
    if not isinstance(case["request"]["body"], str):
        return "the body is generated by the harness (an oversize payload), not sent as is"
    raw = _fill(case["request"]["body"])
    try:
        body = json.loads(raw)
    except ValueError:
        return "the body is not JSON, which no client sends"
    if (
        not isinstance(body, dict)
        or set(body) != {"principal", "epoch", "expected_revision"}
        or not isinstance(body["principal"], str)
        or type(body["epoch"]) is not int
        or body["epoch"] < 0
        or not isinstance(body["expected_revision"], str)
    ):
        return "the incarnation body is not principal, epoch and expected_revision in their forms"
    return "register_incarnation", {"body": body}


def _decide(case: dict) -> tuple[str, dict] | str:
    request = case["request"]
    if request["method"] == "POST" and request["path"].removeprefix(PREFIX) == "/incarnations":
        return _incarnation(case)
    if "$" in request["path"]:
        return "the path names a value the corpus derives"
    return _plan(case)


class Script:
    """A service that plays one case's expectation and records what it was sent."""

    def __init__(self, case: dict, operation: str, arguments: dict):
        self.case, self.operation, self.arguments = case, operation, arguments
        self.requests: list[httpx.Request] = []

    def handle(self, request: httpx.Request) -> httpx.Response:
        self.requests.append(request)
        expect = self.case["expect"]
        if expect["status"] != 200:
            return httpx.Response(
                expect["status"],
                json={
                    "error": {
                        "code": expect["code"],
                        "message": expect["code"],
                        "retryable": expect.get("retryable", False),
                        "requestId": "req-replay",
                        "details": {"reason": expect.get("reason", "")},
                    }
                },
            )
        return httpx.Response(200, json=self._accepted(expect))

    def _accepted(self, expect: dict) -> dict:
        args = self.arguments
        if self.operation == "read_release_catalog":
            return {**self.case["expect"]["body"], "head": HEAD}
        if self.operation == "read_release_catalog_row":
            return {**self.case["expect"]["body"], "head": HEAD}
        reply = {"outcome": expect["outcome"], "revision": _fill(expect["revision"])}
        if self.operation == "register_incarnation":
            reply |= {k: args["body"][k] for k in ("principal", "epoch")}
        elif self.operation == "admit":
            reply |= {"frame_id": args["frame"], "host_id": args["body"].get("host_id", "")}
        else:
            reply |= {"host_id": args["host"]}
        return reply


def _client(script: Script) -> HqServiceAdapter:
    client = httpx.Client(transport=httpx.MockTransport(script.handle), base_url="http://hq")
    return HqServiceAdapter(client, verifier=lambda _method, payload: payload)


def _drive(adapter: HqServiceAdapter, operation: str, arguments: dict):
    if operation == "register_incarnation":
        body = arguments["body"]
        route = (body["principal"], "frame", "host", "inst", body["epoch"], "key")
        return adapter.register_incarnation(
            route,
            expected_revision=body["expected_revision"],
            frame_address="",
            deadline=_later(),
        )
    if operation == "publish_manifest":
        return adapter.publish_manifest(
            arguments["body"], expected_revision=HEAD, deadline=_later()
        )
    if operation == "withdraw_manifest":
        return adapter.withdraw_manifest(
            arguments["host"], expected_revision=HEAD, deadline=_later()
        )
    if operation == "admit":
        body = arguments["body"]
        authority = ObservationAuthority(
            arguments["frame"], body.get("host_id", "host-c"), "inst", "SHA256:k", 0, "hq", "cfg-1"
        )
        request = AdmissionRequest(
            arguments["frame"],
            authority,
            body.get("public_key", ""),
            {},
            admitted=body["kind"] == "open",
        )
        return adapter.admit(
            arguments["frame"],
            request,
            signer=lambda _record: "",
            expected_revision=body["expected_revision"],
            deadline=_later(),
        )
    if operation == "read_release_catalog":
        return adapter.read_release_catalog(arguments["catalog"], deadline=_later())
    return adapter.read_release_catalog_row(
        HEAD, arguments["catalog"], arguments["measured"], deadline=_later()
    )


@pytest.mark.parametrize("name", _names() or ["<no corpus>"])
def test_admission_case_replays_against_the_adapter(name):
    if not _names():
        pytest.skip(f"no admission corpus: set {ENV} to an hq-service export root")
    case = json.loads((_corpus() / f"{name}.json").read_text())
    planned = _decide(case)
    if isinstance(planned, str):
        pytest.skip(planned)
    operation, arguments = planned
    script = Script(case, operation, arguments)
    adapter = _client(script)
    expect = case["expect"]
    if expect["status"] != 200:
        with pytest.raises(FAILURES) as refused:
            _drive(adapter, operation, arguments)
        if not isinstance(refused.value, HqOutcomeUnknown):
            assert (
                expect["code"] in str(refused.value)
                or getattr(refused.value, "code", "") == (expect["code"])
            )
    else:
        result = _drive(adapter, operation, arguments)
        if operation == "read_release_catalog":
            assert result == expect["body"]["rows"]
        elif operation == "read_release_catalog_row":
            assert result == expect["body"]["release"]["row"]
        else:
            assert result == _fill(expect["revision"])
    (sent,) = script.requests
    request = case["request"]
    assert (sent.method, sent.url.path) == (
        request["method"],
        urlsplit(request["path"]).path,
    )
    if request["body"] and "body" in arguments:
        assert json.loads(sent.content) == arguments["body"]
    if urlsplit(request["path"]).query:
        assert parse_qs(sent.url.query.decode()) == parse_qs(urlsplit(request["path"]).query)
